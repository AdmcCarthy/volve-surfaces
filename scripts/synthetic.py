"""Synthetic Volve-like horizons: faulted, folded surfaces on the same grid format as the real build.

    uv run python scripts/synthetic.py [out_dir] [seed]

NOT Volve data and not derived from it: the geology is invented (a dome and a saddle, two normal faults with throw that
grows with depth and tapers along strike, an unconformity, a rotated survey outline, correlated noise, fault gaps).
Used for tests, CI and a "try it without the licensed data" demo. Same manifest schema as `build.py`, so the viewer
loads either set. Deterministic for a given seed.
"""

from __future__ import annotations

import itertools
import json
import sys
from pathlib import Path

import numpy as np
from build import CELL, CRS, NODATA, quantise
from scipy.ndimage import gaussian_filter

# Frame of the same size and place as the real set, so one viewer layout fits both (ED50 / UTM 31N metres).
X0, Y0, NX, NY = 429650.0, 6482150.0, 415, 285
ANGLE = np.deg2rad(-20)  # survey rotation
HALF_U, HALF_V = 4200.0, 2100.0  # survey half-extent in rotated metres
WATER = 92.0

ATTRIBUTION = (
    "Synthetic data generated by this repository (MIT licence). Not Volve data, not derived from it, "
    "and not geologically meaningful."
)

# (id, label, domain, unit) in depth order, shallow to deep.
LAYERS = ["seabed", "ty", "shetland", "bcu", "hugin_top", "hugin_base"]
LABELS = {
    "seabed": "Seabed (synthetic)",
    "ty": "Ty Fm top (synthetic)",
    "shetland": "Shetland Gp top (synthetic)",
    "bcu": "Base Cretaceous unconformity (synthetic)",
    "hugin_top": "Hugin Fm top (synthetic)",
    "hugin_base": "Hugin Fm base (synthetic)",
}
TWT_LAYERS = ["ty", "shetland", "bcu", "hugin_top", "hugin_base"]


def coords() -> tuple[np.ndarray, np.ndarray, np.ndarray, np.ndarray]:
    """Cell-centre x, y and rotated (u, v) in metres relative to the frame centre."""
    gx = X0 + (np.arange(NX) + 0.5) * CELL
    gy = Y0 - (np.arange(NY) + 0.5) * CELL
    xx, yy = np.meshgrid(gx, gy)
    dx, dy = xx - (X0 + NX * CELL / 2), yy - (Y0 - NY * CELL / 2)
    c, s = np.cos(ANGLE), np.sin(ANGLE)
    return xx, yy, c * dx + s * dy, -s * dx + c * dy


def gauss(u, v, u0, v0, su, sv):
    return np.exp(-((u - u0) ** 2 / (2 * su**2) + (v - v0) ** 2 / (2 * sv**2)))


def fault_offset(u, v, p0, p1, throw, width=40.0):
    """Normal-fault step across the line p0->p1 (rotated metres): throw tapers to zero at both tips.

    Returns (offset applied to the downthrown side, signed distance to the fault trace in metres).
    """
    d = np.array(p1) - np.array(p0)
    length = np.hypot(*d)
    t = ((u - p0[0]) * d[0] + (v - p0[1]) * d[1]) / length**2
    dist = ((u - p0[0]) * -d[1] + (v - p0[1]) * d[0]) / length
    taper = (
        np.sin(np.pi * np.clip(t, 0, 1)) ** 1.5
    )  # gradient is zero at the tips: no cliff across the strike
    step = 0.5 * (1 + np.tanh(dist / width))
    return throw * taper * step, dist, taper


# the two normal faults of surfaces(), end points in rotated metres (u, v); throw is down to the left of p0 -> p1
FAULTS = {"F1": ((-1800, -1700), (500, 1500)), "F2": ((900, -1900), (1500, 1800))}


def faults_record() -> dict:
    """The synthetic faults as normalised records (docs/modules.md): known type and downthrown side, in the same frame."""
    xc, yc, c, s = X0 + NX * CELL / 2, Y0 - NY * CELL / 2, np.cos(ANGLE), np.sin(ANGLE)

    def to_xy(u, v):
        return [
            round(float(xc + c * u - s * v), 1),
            round(float(yc + s * u + c * v), 1),
        ]

    feats = [
        {"id": f"trace:synthetic:{k}", "kind": "trace", "name": f"Synthetic fault {k}", "type": "normal", "certainty": "certain",
         "downthrown": "left", "domain": "depth", "xy": [to_xy(*p0), to_xy(*p1)]}
        for k, (p0, p1) in FAULTS.items()
    ]  # fmt: skip
    return {"crs": CRS, "source_crs": None, "synthetic": True, "attribution": ATTRIBUTION,
            "note": "Invented fault traces, with type and downthrown side as the generator made them.", "features": feats}  # fmt: skip


def contacts_record(seed: int = 7) -> dict:
    """Synthetic contacts: a gas cap over an oil leg in the west segment, oil only (a different contact) in the east.

    F2 is the sealing barrier between the segments; each seed is the crest of its high. The contacts are chosen relative to the
    crest depths so the fills are closed inside the survey. Shows what the Volve documents cannot: dual-phase and unequal contacts.
    """
    z, survey, gap = surfaces(seed)
    zt = np.where(
        survey & ~gap, z["hugin_top"], np.nan
    )  # the grid as written: fault gaps are nodata
    xx, yy, u, v = coords()
    xc, yc, c, s = X0 + NX * CELL / 2, Y0 - NY * CELL / 2, np.cos(ANGLE), np.sin(ANGLE)

    def crest(u0, v0, radius):
        near = (np.hypot(u - u0, v - v0) < radius) & survey
        r, k = np.unravel_index(np.nanargmin(np.where(near, zt, np.nan)), zt.shape)
        return [round(float(xx[r, k]), 1), round(float(yy[r, k]), 1)], float(zt[r, k])

    (west_xy, west_z), (east_xy, east_z) = crest(-700, 150, 900), crest(1900, -300, 700)
    (u0, v0), (u1, v1) = FAULTS["F2"]
    d = np.array([u1 - u0, v1 - v0], float)
    d /= np.hypot(*d)
    a, b = (
        np.array([u0, v0]) - 400 * d,
        np.array([u1, v1]) + 400 * d,
    )  # F2 extended past its tips so it divides the survey
    to_xy = lambda p: [
        round(float(xc + c * p[0] - s * p[1]), 1),
        round(float(yc + s * p[0] + c * p[1]), 1),
    ]
    # a trap is closed only below its spill point: the deepest level at which the fill from the crest stays inside the survey, the
    # barrier included. Contacts are set below it by a margin so the example is a closed accumulation, not a leaking one.
    from scipy import ndimage as ndi

    block = np.zeros(zt.shape, bool)
    for t in np.linspace(0, 1, 400):
        pu, pv = a + t * (b - a)
        px_, py_ = to_xy((pu, pv))
        r, k = int((Y0 - py_) / CELL), int((px_ - X0) / CELL)
        if 0 <= r < zt.shape[0] and 0 <= k < zt.shape[1]:
            block[r, k] = True
    block = ndi.binary_dilation(block, iterations=1)
    outside = ndi.binary_dilation(~survey, iterations=1)

    def spill(xy):
        r, k = int((Y0 - xy[1]) / CELL), int((xy[0] - X0) / CELL)
        for level in range(int(np.ceil(zt[r, k])), int(np.nanmax(zt))):
            lab, _ = ndi.label((zt <= level) & ~block)
            comp = lab == lab[r, k]
            if (comp & outside).any():
                return level - 1
        return int(np.nanmax(zt))

    spill_w, spill_e = spill(west_xy), spill(east_xy)
    owc_w, owc_e = (
        min(round(west_z + 115), spill_w - 20),
        min(round(east_z + 65), spill_e - 15),
    )
    goc = round(west_z + 0.45 * (owc_w - west_z))
    return {
        "crs": CRS, "synthetic": True, "attribution": ATTRIBUTION, "reservoir": "Hugin Fm (synthetic)", "horizon": "hugin_top",
        "datum": "synthetic (metres below an arbitrary datum)", "outline": None,
        "segments": [{"id": "west", "name": "West segment", "well": None, "seed": west_xy, "note": "Gas cap over an oil leg."},
                     {"id": "east", "name": "East segment", "well": None, "seed": east_xy, "note": "Oil only, a different contact."}],
        "barriers": [{"id": "F2", "name": "Fault F2 (sealing)", "kind": "fault", "accuracy_m": 0, "note": "Synthetic sealing fault.", "xy": [to_xy(a), to_xy(b)]}],
        "evidence": [], "minimum_contacts": [], "checks": [],
        "cases": [{"id": "model", "label": "Synthetic: gas cap and oil leg (west), oil (east)", "status": "synthetic", "date": None,
                   "note": f"Invented contacts, below the spill points ({spill_w} and {spill_e} m) so both accumulations are closed. The two segments cannot merge across F2, so each keeps its own contact.",
                   "contacts": [{"kind": "GOC", "depth": goc, "segment": "west", "basis": "synthetic", "confidence": "Synthetic", "source": "synthetic generator"},
                                {"kind": "OWC", "depth": owc_w, "segment": "west", "range": {"min": owc_w - 15, "likely": owc_w, "max": owc_w + 20}, "basis": "synthetic", "confidence": "Synthetic", "source": "synthetic generator"},
                                {"kind": "OWC", "depth": owc_e, "segment": "east", "range": {"min": owc_e - 10, "likely": owc_e, "max": owc_e + 20}, "basis": "synthetic", "confidence": "Synthetic", "source": "synthetic generator"}]}],
    }  # fmt: skip


def surfaces(seed: int = 7):
    """Depth surfaces (m, positive down) per layer and the fault-gap mask; all shape (NY, NX)."""
    rng = np.random.default_rng(seed)
    _, _, u, v = coords()

    def noise(amp, sigma):
        n = gaussian_filter(rng.standard_normal(u.shape), sigma)
        return amp * n / n.std()

    # Structure: regional dip to the east, a dome, a smaller satellite high, a saddle between them.
    structure = (
        -300 * gauss(u, v, -700, 150, 1300, 800)
        - 190 * gauss(u, v, 1900, -300, 700, 550)
        + 8 * (u / 1000)
        + 6 * (v / 1000)
    )
    f1, d1, tp1 = fault_offset(u, v, *FAULTS["F1"], throw=1.0)  # main fault
    f2, _d2, tp2 = fault_offset(u, v, *FAULTS["F2"], throw=1.0)  # smaller fault

    z, gap = {}, np.zeros(u.shape, bool)
    # layer: (mean depth, structural gain, fault throw m, noise m)
    spec = {
        "seabed": (None, 0, 0, 0.3),
        "ty": (2445, 0.30, 12, 1.0),
        "shetland": (2585, 0.35, 18, 1.0),
        "bcu": (2985, 1.25, 55, 2.5),
        "hugin_top": (3060, 1.30, 70, 3.0),
        "hugin_base": (3150, 1.30, 75, 3.0),
    }
    for name in LAYERS:
        mean, gain, throw, nz = spec[name]
        if name == "seabed":
            z[name] = WATER - 8 * (u / 4000) - 3 * (v / 2000) + noise(nz, 6)
            continue
        z[name] = mean + gain * structure + throw * (f1 + 0.5 * f2) + noise(nz, 3)
        heave = 0.58 * throw * (tp1 * (abs(d1) < 1500) + 0.5 * tp2)
        gap |= (
            (np.abs(d1) < np.maximum(heave * 0.5, 0.9 * CELL))
            & (tp1 > 0.05)
            & (throw > 40)
        )
    # Thickness changes: Hugin base thins over the high; keep every layer strictly below the one above.
    z["hugin_base"] = np.maximum(z["hugin_base"], z["hugin_top"] + 15)
    for upper, lower in itertools.pairwise(LAYERS):
        z[lower] = np.maximum(z[lower], z[upper] + 20)

    survey = (np.abs(u) < HALF_U) & (np.abs(v) < HALF_V)
    return z, survey, gap


def to_twt(z: np.ndarray) -> np.ndarray:
    """Two-way time (ms): water at 1480 m/s, then a simple compaction trend. Not calibrated to Volve."""
    below = np.maximum(z - WATER, 0)
    return 2000 * WATER / 1480 + 2000 * below / (1700 + 0.2 * below)


def build(out_dir: str = "data/synthetic", seed: int = 7) -> None:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    z, survey, gap = surfaces(seed)
    entries = []
    jobs = [(f"{n}_depth", n, "depth", "m", z[n]) for n in LAYERS]
    jobs += [(f"{n}_twt", n, "twt", "ms", to_twt(z[n])) for n in TWT_LAYERS]
    for hid, n, domain, unit, grid in jobs:
        grid = np.where(
            survey & ~(gap & (n in ("bcu", "hugin_top", "hugin_base"))), grid, np.nan
        )
        q, zmin, zmax, scale = quantise(grid)
        (out / f"{hid}.bin").write_bytes(q.tobytes())
        entries.append(
            {
                "id": hid,
                "label": LABELS[n],
                "domain": domain,
                "unit": unit,
                "file": f"{hid}.bin",
                "source": "synthetic",
                "valid_cells": int(np.sum(q != NODATA)),
                "fill": round(float(np.mean(q != NODATA)), 4),
                "z_min": round(zmin, 2),
                "z_max": round(zmax, 2),
                "offset": zmin,
                "scale": scale,
            }
        )
        print(
            f"wrote {hid}: fill {entries[-1]['fill']:.0%}, {zmin:.0f} to {zmax:.0f} {unit}",
            flush=True,
        )
    manifest = {
        "synthetic": True,
        "crs": CRS,
        "cell": CELL,
        "origin": {
            "x": X0,
            "y": Y0,
            "note": "west edge, north edge; row 0 is the northernmost row",
        },
        "nx": NX,
        "ny": NY,
        "dtype": "uint16-le",
        "nodata": NODATA,
        "vertical_datum": "synthetic (metres below an arbitrary datum)",
        "confidence": "Synthetic",
        "seed": seed,
        "attribution": ATTRIBUTION,
        "horizons": entries,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    (out / "faults.json").write_text(
        json.dumps(faults_record(), separators=(",", ":")), encoding="utf-8"
    )
    (out / "contacts.json").write_text(
        json.dumps(contacts_record(seed), separators=(",", ":")), encoding="utf-8"
    )


if __name__ == "__main__":
    build(
        sys.argv[1] if len(sys.argv) > 1 else "data/synthetic",
        int(sys.argv[2]) if len(sys.argv) > 2 else 7,
    )
